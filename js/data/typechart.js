// 单一属性打击倍率；defTypes 可为多属性，返回各倍率乘积（0 即免疫）
function typeEffectiveness(moveType, defTypes) {
  let mult = 1;
  for (let i = 0; i < defTypes.length; i++) {
    const key = moveType + ':' + defTypes[i];
    if (Object.prototype.hasOwnProperty.call(TYPE_CHART, key)) {
      mult *= TYPE_CHART[key];
    }
  }
  return mult;
}

